import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { zipSync, strToU8 } from "fflate";
import { validateMetadata, parameterValues, safePath } from "../src/studio/contracts.ts";
import { importShare, exportShare } from "../src/studio/share.ts";
import { requireDesktop } from "../src/studio/execution.ts";

const scene={version:1,id:"test",title:"Actual scene",description:"Test",entry:"main.py",scene:"MyScene",license:"CC0-1.0",concept_ids:["simple-harmonic-motion"],learning_objectives:["Observe period"],parameters:{omega:{type:"number",min:0.1,max:8,default:2}}};
validateMetadata(scene);
assert.throws(()=>validateMetadata({...scene,concept_ids:undefined}));
assert.throws(()=>validateMetadata({...scene,learning_objectives:undefined}));
for(const name of ["../x","/x","C:/x","a\\b","a//b","a/./b","nul.txt","a.","a\0b"])assert.throws(()=>safePath(name));
for(const patch of [{version:2},{concept_ids:["invented-concept"]},{entry:"../main.py"},{scene:"Bad;Name"},{parameters:{bad:{type:"number",min:0,max:1,default:2}}}])assert.throws(()=>validateMetadata({...scene,...patch}));
assert.deepEqual(parameterValues(scene.parameters,{}),{omega:2});
for(const value of [true,"2",NaN,Infinity,9])assert.throws(()=>parameterValues(scene.parameters,{omega:value}));
assert.throws(()=>parameterValues(scene.parameters,{unknown:2}));
const data=strToU8('from manimlib import *\n# never executed\nprint("do not run")\n');
const bytes=await exportShare(scene,[{path:"source/main.py",role:"source",data}]);
const imported=await importShare(bytes);
assert.deepEqual(imported.manifest.scene,scene);
assert.equal(new TextDecoder().decode(imported.files["source/main.py"]),new TextDecoder().decode(data));
const exported=await exportShare(scene,[]);
assert.equal((await importShare(exported)).manifest.files.length,0,"source must be opt-in");
for(const files of [{"../escape.py":data},{"main.py":data,"MAIN.py":data},{"manifest.json":strToU8('{"version":999}')},{"a":data,"a/b":data}])await assert.rejects(importShare(zipSync(files)));
const bad={...imported.manifest,files:imported.manifest.files.map(f=>({...f,sha256:"0".repeat(64)}))};
await assert.rejects(importShare(zipSync({"manifest.json":strToU8(JSON.stringify(bad)),"source/main.py":data})),/corrupted/);
await assert.rejects(exportShare(scene,[{path:"evil.html",role:"source",data}]));
const config=JSON.parse(await readFile("src-tauri/tauri.conf.json","utf8"));
assert.equal(config.identifier,"org.stemvisualexplorer.app","preserve desktop data identity");
const commands=await readFile("src/lib/commands.ts","utf8");
for(const key of ["sve.settings","sve.favorites","sve.history"])assert.ok(commands.includes(key),`preserve ${key}`);
assert.throws(()=>requireDesktop(false),/only in the desktop app/,"Web may never invoke Python execution");
assert.doesNotThrow(()=>requireDesktop(true));
process.stdout.write(String("STUDIO: metadata, canonical concepts, parameters, archive versions/paths/hashes/types, opt-in source, execution boundary and storage identity PASS")+"\n");

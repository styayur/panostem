import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { importShare, exportShare } from '../src/studio/share.ts';
const read = file => readFile(file, 'utf8');
const config = JSON.parse(await read('src-tauri/tauri.conf.json'));
assert.equal(config.productName, 'Vextessera');
assert.equal(config.identifier, 'org.stemvisualexplorer.app');
const old = new Uint8Array(await readFile('tests/fixtures/migration/oscillator-alpha2.panostem.zip'));
const provenance = JSON.parse(await read('tests/fixtures/migration/provenance.json'));
assert.equal(createHash('sha256').update(old).digest('hex'), provenance.share.sha256);
const share = await importShare(old);
assert.equal(share.manifest.format, 'panostem-share');
assert.equal(share.manifest.scene.id, 'panostem-example-oscillator');
assert.ok(share.files['source/main.py']);
assert.ok(share.files['media/oscillator.mp4']);
const roundTrip = await importShare(await exportShare(share.manifest.scene, share.manifest.files.map(file => ({path:file.path, role:file.role, data:share.files[file.path]}))));
assert.deepEqual(roundTrip.manifest.scene, share.manifest.scene);
assert.deepEqual(roundTrip.files['source/main.py'], share.files['source/main.py']);
// Keep compatibility identities explicit even though public branding changes.
const commands = await read('src/lib/commands.ts');
for (const key of ['sve.settings','sve.favorites','sve.history']) assert.ok(commands.includes(`"${key}"`));
const studio = await read('src/studio/StudioPage.tsx');
assert.ok(studio.includes('"panostem.project-path"'));
assert.ok((await read('src-tauri/src/state.rs')).includes('app_dir.join("sve.db")'));
assert.ok((await read('src-tauri/src/lib.rs')).includes('app_dir.join("panostem-runtime")'));
assert.ok((await read('src/studio/backend.ts')).includes('"panostem-media"'));
assert.ok((await read('src-tauri/runtime/controller.py')).includes('"panostem.json"'));
process.stdout.write('MIGRATION: authentic alpha.2 share bytes/read/export, legacy data/runtime/protocol identities PASS\n');
